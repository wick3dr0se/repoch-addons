--[[
Record where every database file came from, and prove it later.

The rule this file exists to enforce: we do not maintain an Epoch database.
pfQuest-epoch is the thing that tracks server content, shagu's pfQuest is the
frozen WotLK base, and our job is to consume both verbatim. The moment somebody
hand-edits a vendored db file, an upstream refresh turns into a merge, and the
data drifts. So:

  1. every db file is recorded here with its source repo, commit and checksum
  2. tests/db_provenance_spec.lua fails if a committed file stops matching
  3. genuine local corrections live in data/local/ instead, as an explicit overlay

Refresh the lock after pulling a new upstream commit:

    lua5.1 tools/lock_data.lua            # rewrite data/upstream.lock
    lua5.1 tools/sync_data.lua --update   # fetch the pinned commits into db/
]]

local SOURCES = {
	base = {
		repo = "https://github.com/shagu/pfQuest",
		commit = "104f35678ca39ab1fb78b655f815cc7016f5e0c8",
		date = "2025-08-25",
		note = "Frozen WotLK data. Only bump when shagu ships a fix, which is rare.",
		-- shagu also ships TBC variants; this addon is 3.3.5a only
		skip = { "%(items|units|objects|quests|zones|professions)%(%-tbc%)%.lua" },
	},
	epoch = {
		repo = "https://github.com/Bennylavaa/pfQuest-epoch",
		commit = "5c64470c217cef35a2dd565122481f2a1e004f69",
		date = "2026-09-09",
		note = "The live part: Epoch quests, spawns, drops. Bump this when server content changes.",
		skip = {},
	},
}

---------------------------------------------------------------------------
-- checksum: change detection, not security
---------------------------------------------------------------------------

local function checksum(text)
	local h = 5381
	for i = 1, #text do
		h = (h * 33 + text:byte(i)) % 4294967296
	end
	return string.format("%08x", h)
end

local function readAll(path)
	local f = io.open(path, "rb")
	if not f then return nil end
	local s = f:read("*a")
	f:close()
	return s
end

local function walk(dir, out)
	out = out or {}
	local pipe = io.popen('find "' .. dir .. '" -name "*.lua" 2>/dev/null')
	if not pipe then return out end
	for path in pipe:lines() do out[#out + 1] = path end
	pipe:close()
	table.sort(out)
	return out
end

local function skipped(path, patterns)
	for _, pattern in ipairs(patterns or {}) do
		if path:match(pattern) then return true end
	end
	return false
end

---------------------------------------------------------------------------
-- classify a file by which source it belongs to
---------------------------------------------------------------------------

local function sourceFor(path)
	-- epoch overlay files carry the suffix; everything else is the shagu base
	if path:match("%-epoch%.lua$") then
		return "epoch"
	end
	if path:match("%-tbc%.lua$") then
		return nil -- not shipped
	end
	return "base"
end

---------------------------------------------------------------------------

local files = walk("db")
local lock = {}
local counts = { base = 0, epoch = 0, skipped = 0 }

for _, path in ipairs(files) do
	if not path:match("^db/packed/") then
		local owner = sourceFor(path)
		if owner then
			local body = readAll(path)
			if body then
				lock[#lock + 1] = { path = path, source = owner, checksum = checksum(body), bytes = #body }
				counts[owner] = counts[owner] + 1
			end
		else
			counts.skipped = counts.skipped + 1
		end
	end
end

if #lock == 0 then
	error("no database files found under db/ (run from the addon root)")
end

local out = {
	"--[[",
	"Generated by tools/lock_data.lua. Do not edit.",
	"",
	"Provenance for every vendored database file: which upstream repo and commit it",
	"came from, and the checksum it had there. tests/db_provenance_spec.lua compares",
	"the committed files against this, so a hand edit is caught instead of becoming",
	"a merge conflict on the next refresh. Put real corrections in data/local/.",
	"]]",
	"return {",
	"\tsources = {",
}

for _, name in ipairs({ "base", "epoch" }) do
	local s = SOURCES[name]
	out[#out + 1] = string.format('\t\t%s = {', name)
	out[#out + 1] = string.format('\t\t\trepo = "%s",', s.repo)
	out[#out + 1] = string.format('\t\t\tcommit = "%s",', s.commit)
	out[#out + 1] = string.format('\t\t\tdate = "%s",', s.date)
	out[#out + 1] = string.format('\t\t\tnote = %q,', s.note)
	out[#out + 1] = "\t\t},"
end

out[#out + 1] = "\t},"
out[#out + 1] = "\tfiles = {"

for _, entry in ipairs(lock) do
	out[#out + 1] = string.format('\t\t{ path = "%s", source = "%s", checksum = "%s", bytes = %d },',
		entry.path, entry.source, entry.checksum, entry.bytes)
end

out[#out + 1] = "\t},"
out[#out + 1] = "}"

os.execute("mkdir -p data")
local f = assert(io.open("data/upstream.lock", "wb"))
f:write(table.concat(out, "\n"), "\n")
f:close()

print(string.format("data/upstream.lock: %d files recorded (%d base, %d epoch, %d unshipped)",
	#lock, counts.base, counts.epoch, counts.skipped))
print("  base  " .. SOURCES.base.repo .. " @ " .. SOURCES.base.commit:sub(1, 7) .. "  " .. SOURCES.base.date)
print("  epoch " .. SOURCES.epoch.repo .. " @ " .. SOURCES.epoch.commit:sub(1, 7) .. "  " .. SOURCES.epoch.date)
